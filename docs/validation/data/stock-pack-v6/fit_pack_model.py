import statistics as st
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[3]
V5 = HERE.parent / 'stock-startup-v5'
JAVA = ROOT / 'src/com/jjricks/volt/Ut5MaxStockPackModel.java'
PARITY = ROOT / 'tests/StockPackParity.java'
RESULTS = HERE / 'evaluation.json'

RATED = 15.3          # UT5 MAX reported capacity; every input here reports 15.3 Ah
REF_AMPS = 1.94       # settled stock-charger current used as the voltage reference
IR_OHMS = 0.2         # pack terminal-voltage compensation for different live currents
VOLT_SIGMA = 0.15     # volts of pack-to-pack/temperature uncertainty in the voltage lookup
LOW_VOLT_SIGMA = 0.5  # packs differ more near empty, so trust voltage less below LOW_VOLTS
LOW_VOLTS = 48.5      # the extra uncertainty ramps in over the volt below this
GAUGE_FADE_VOLTS = 53.3  # the gauge's catch-up has begun: stop trusting its percentage
TAU = 25.0            # minutes; stock charger warm-up current decay time constant
JUMP_VOLTS = 53.0     # the gauge's late catch-up starts near this pack voltage
EDGE_VOLTS = 0.3
BIN_VOLTS = 0.05


def num(x):
    return float(x) if x not in ('', None) else None


def load_charges():
    """Completed standard-charger charges as ordered samples: minutes, soc, volts, amps."""
    charges = {}
    for path in sorted((V5 / 'scooter-a').glob('points-*.csv')):
        for r in csv.DictReader(open(path, newline='')):
            if r['charger'] != 'STOCK':
                continue
            charges.setdefault('A:' + r['case'], []).append(r)
    out = {}
    for name, rows in charges.items():
        if not any(r['truth_full'] for r in rows):
            continue  # incomplete journals have no observed finish
        rows.sort(key=lambda r: float(r['physical_elapsed_ms']))
        out[name] = [dict(t=float(r['physical_elapsed_ms']) / 60000, soc=float(r['soc']), v=float(r['volts']),
                          i=abs(float(r['amps'])), tf=num(r['truth_full']), t80=num(r['truth80']), t95=num(r['truth95']))
                     for r in rows]
    b = list(csv.DictReader(open(V5 / 'scooter-b/paired-input.csv', newline='')))
    out['B'] = [dict(t=float(r['elapsed_ms']) / 60000, soc=float(r['soc']), v=float(r['volts']), i=abs(float(r['amps'])),
                     tf=num(r['truth_full']), t80=num(r['truth80']), t95=num(r['truth95'])) for r in b]
    for rows in out.values():
        annotate(rows)
    return out


def annotate(rows):
    """Ah still to deliver before the gauge first shows 99%, plus finish and milestone timing."""
    cum = [0.0]
    for a, b in zip(rows, rows[1:]):
        cum.append(cum[-1] + (b['t'] - a['t']) / 60 * (a['i'] + b['i']) / 2)  # gaps keep charging
    k99 = next(k for k, r in enumerate(rows) if r['soc'] >= 99)
    t99 = rows[k99]['t']
    for k, r in enumerate(rows):
        r['q99'] = cum[k99] - cum[k] if k < k99 else 0.0
    first = {}
    for r in rows:
        first.setdefault(r['soc'], r['t'])
    meta = rows[0]
    meta['_finish'] = first[100] - t99
    meta['_lead'] = {s: t99 - first[s] for s in range(89, 99) if s in first}
    meta['_jump_lead'] = t99 - next(r['t'] for r in rows if r['v'] >= JUMP_VOLTS)
    meta['_start'] = rows[0]['soc']
    meta['_offset'] = rows[0]['soc'] + rows[0]['q99'] / RATED * 100  # gauge-equivalent SOC of the 99% knee


def pav_table(points):
    """Non-increasing Ah-to-knee as pack voltage rises: pool-adjacent-violators on bin medians."""
    bins = {}
    for vc, q in points:
        bins.setdefault(round(vc / BIN_VOLTS) * BIN_VOLTS, []).append(q)
    blocks = [[st.median(bins[x]), len(bins[x]), [x]] for x in sorted(bins)]
    k = 0
    while k < len(blocks) - 1:
        if blocks[k][0] < blocks[k + 1][0]:
            a, b = blocks[k], blocks[k + 1]
            w = a[1] + b[1]
            blocks[k] = [(a[0] * a[1] + b[0] * b[1]) / w, w, a[2] + b[2]]
            del blocks[k + 1]
            k = max(k - 1, 0)
        else:
            k += 1
    return [[round(st.mean(m), 4), round(q, 4)] for q, _, m in blocks]


def decay_fit(rows):
    """Per-charge warm-up amplitude K in I = I_settled * (1 + K exp(-age/TAU))."""
    late = [r['i'] for r in rows if r['t'] - rows[0]['t'] >= 120 and r['soc'] < 89]
    if len(late) < 20:
        return None
    settled = st.median(late)
    obs = [(r['t'] - rows[0]['t'], r['i'] / settled) for r in rows if r['soc'] < 89]
    best = min((sum((y - 1 - k * math.exp(-a / TAU)) ** 2 for a, y in obs), k) for k in [x / 200 for x in range(0, 81)])
    return best[1]


def fit(charges):
    pts = [(r['v'] - IR_OHMS * (r['i'] - REF_AMPS), r['q99']) for rows in charges.values() for r in rows if r['q99'] > 0]
    low = [rows[0] for rows in charges.values() if rows[0]['_start'] < 80]
    depth = [100 - m['_start'] for m in low]
    offset = [m['_offset'] for m in low]
    dm, om = st.mean(depth), st.mean(offset)
    slope = sum((d - dm) * (o - om) for d, o in zip(depth, offset)) / sum((d - dm) ** 2 for d in depth)
    slope = min(0.0, slope)  # a deeper discharge can only enlarge the late gauge catch-up
    residual = max(abs(o - (om + slope * (d - dm))) for d, o in zip(depth, offset))
    ks = [k for k in (decay_fit(rows) for rows in charges.values()) if k is not None]
    by_scooter = {}
    for name, rows in charges.items():
        k = decay_fit(rows)
        if k is not None:
            by_scooter.setdefault(name.split(':')[0], []).append(k)
    finishes = [rows[0]['_finish'] for rows in charges.values()]
    leads = {s: [rows[0]['_lead'][s] for rows in charges.values() if s in rows[0]['_lead']] for s in range(89, 99)}
    return {
        'table': pav_table(pts),
        'offset_mean': om, 'offset_depth_slope': slope, 'depth_mean': dm,
        'depth_min': min(depth), 'depth_max': max(depth),
        'offset_residual': residual,
        'gauge_sigma': max(0.35, st.pstdev(offset) * RATED / 100),
        'decay_display': st.mean(st.mean(v) for v in by_scooter.values()),
        'decay_planning': max(ks) + 0.02,
        'finish_display': st.mean(finishes), 'finish_planning': max(finishes) + 2.0,
        'lead_display': [st.median(leads[s]) for s in range(89, 99)],
        'lead_planning': [min(leads[s]) for s in range(89, 99)],
        'jump_lead': st.median(rows[0]['_jump_lead'] for rows in charges.values()),
        'jump_lead_planning': min(rows[0]['_jump_lead'] for rows in charges.values()),
    }


# ---- Model evaluation. Ut5MaxStockPackModel.java implements exactly these steps. ----

def table_q(m, vc):
    x = [p[0] for p in m['table']]; y = [p[1] for p in m['table']]
    if vc <= x[0]:
        return y[0]
    if vc >= x[-1]:
        return y[-1]
    k = bisect.bisect_left(x, vc)
    return y[k - 1] + (vc - x[k - 1]) / (x[k] - x[k - 1]) * (y[k] - y[k - 1])


def knot_slope(x, y, k):
    lo, hi = max(0, k - 3), min(len(x) - 1, k + 3)
    return abs((y[hi] - y[lo]) / (x[hi] - x[lo])) if x[hi] > x[lo] else 0.0


def table_slope(m, vc):
    """Local |dAh/dV|, interpolated between knots so voltage trust changes continuously."""
    x = [p[0] for p in m['table']]; y = [p[1] for p in m['table']]
    if vc <= x[0]:
        return knot_slope(x, y, 0)
    if vc >= x[-1]:
        return knot_slope(x, y, len(x) - 1)
    k = bisect.bisect_left(x, vc)
    a, b = knot_slope(x, y, k - 1), knot_slope(x, y, k)
    return a + (vc - x[k - 1]) / (x[k] - x[k - 1]) * (b - a)


def gauge_offset(m, start_soc):
    depth = min(max(100 - start_soc, m['depth_min']), m['depth_max'])
    return m['offset_mean'] + m['offset_depth_slope'] * (depth - m['depth_mean'])


def knee_ah(m, soc, volts, amps, start_soc, rated, planning):
    offset = gauge_offset(m, start_soc) + (m['offset_residual'] + 1.0 if planning else 0.0)
    qg = max(0.0, rated * (offset - soc) / 100)
    vc = volts - IR_OHMS * (amps - REF_AMPS)
    trust = min(1.0, max(0.0, (GAUGE_FADE_VOLTS - vc) / EDGE_VOLTS))
    if trust <= 0:
        return table_q(m, vc)  # after the catch-up begins only voltage counts, clamped at the table's end
    x0, xn = m['table'][0][0], m['table'][-1][0]
    edge = min(1.0, (vc - x0) / EDGE_VOLTS, (xn - vc) / EDGE_VOLTS)
    if edge <= 0:
        return qg
    qv = table_q(m, vc)
    volt_sigma = VOLT_SIGMA + (LOW_VOLT_SIGMA - VOLT_SIGMA) * min(1.0, max(0.0, LOW_VOLTS - vc))
    sv = (table_slope(m, vc) * volt_sigma + 0.08) / max(edge, 1e-3)
    sg = m['gauge_sigma'] / trust
    wv, wg = 1 / sv ** 2, 1 / sg ** 2
    return (qv * wv + qg * wg) / (wv + wg)


def minutes_for(ah, amps, age, k):
    """Minutes to deliver ah while the warm-up current decays toward its settled level."""
    if ah <= 0:
        return 0.0
    settled = amps / (1 + k * math.exp(-age / TAU))
    need = ah * 60
    head = k * TAU * math.exp(-age / TAU)
    lo, hi = 0.0, 6000.0
    for _ in range(64):
        mid = (lo + hi) / 2
        if settled * (mid + head * (1 - math.exp(-mid / TAU))) < need:
            lo = mid
        else:
            hi = mid
    return hi


def lead(m, target, planning):
    table = m['lead_planning' if planning else 'lead_display'] + [0.0]
    k = int(math.floor(target)) - 89
    f = target - math.floor(target)
    return table[k] + (table[k + 1] - table[k]) * f


PLAUSIBLE_FRACTION = 0.25  # voltage and gauge never disagree by a quarter of the pack in real charges


def plausible(m, soc, volts, amps, start_soc, rated):
    """Reject contradictory readings (for example near-full voltage with a half-empty gauge)."""
    gauge = max(0.0, rated * (gauge_offset(m, start_soc) - soc) / 100)
    return abs(table_q(m, volts - IR_OHMS * (amps - REF_AMPS)) - gauge) <= PLAUSIBLE_FRACTION * rated


def estimate(m, soc, target, volts, amps, age, start_soc, rated=RATED, planning=False):
    if not plausible(m, soc, volts, amps, start_soc, rated):
        raise ValueError('implausible reading in the published measurements')
    if target <= soc:
        return 0.0
    k = m['decay_planning' if planning else 'decay_display']
    t99 = minutes_for(knee_ah(m, soc, volts, amps, start_soc, rated, planning), amps, age, k)
    if target >= 100:
        return t99 + m['finish_planning' if planning else 'finish_display']
    if target >= 99:
        return t99
    # The gauge reaches a cutoff by steady counting or by its late catch-up, whichever is first.
    counted = minutes_for(rated * (target - soc) / 100, amps, age, k)
    if target >= 89:
        caught = max(0.0, t99 - lead(m, target, planning))
    else:
        caught = max(0.0, t99 - m['jump_lead_planning' if planning else 'jump_lead'] + (3.0 if planning else 2.0))
    return min(counted, caught)


AGE_GRID = [0, 5, 10, 15, 20, 30, 40, 50, 60, 80, 100, 130, 160, 200, 1e9]
AGE_INFERENCE_MINUTES = 10


def infer_start_age(m, watched, amps):
    """Charge age at first sight from watched current; mirrors ChargeProgressTracker/Java."""
    if len(watched) < 2 or watched[-1] - watched[0] < 8:
        return 0.0
    best_error, best = math.inf, 0.0
    k = m['decay_display']
    for a0 in AGE_GRID:
        shape = [1 + k * math.exp(-(a0 + t) / TAU) for t in watched]
        settled = sum(a * s for a, s in zip(amps, shape)) / sum(s * s for s in shape)
        error = sum((a - settled * s) ** 2 for a, s in zip(amps, shape))
        if error < best_error - 1e-12:
            best_error, best = error, a0
    return min(best, 600.0)


def evaluate_first_sight(charges, model_for, watch):
    """The app first sees an already-running charge, then watches its current for watch minutes."""
    err = {'display': {100: [], 95: [], 80: []}, 'planning': {100: [], 95: [], 80: []}}
    for name, rows in charges.items():
        m = model_for(name)
        for s in range(0, len(rows), 10):
            sight = rows[s]
            if sight['soc'] >= 85:
                continue
            watched, amps, last = [], [], None
            for r in rows[s:]:
                if r['t'] - sight['t'] > watch:
                    break
                if last is None or r['t'] - last >= 0.5:  # the app keeps one sample per 30 s
                    watched.append(r['t'] - sight['t']); amps.append(r['i']); last = r['t']
            now = next((r for r in rows[s:] if r['t'] - sight['t'] >= watch), None)
            if now is None or now['soc'] >= 89:
                continue
            elapsed = now['t'] - sight['t']
            age = (infer_start_age(m, watched, amps) if elapsed >= AGE_INFERENCE_MINUTES else 0.0) + elapsed
            for target, key in ((100, 'tf'), (95, 't95'), (80, 't80')):
                if now[key] is None or now[key] <= 0:
                    continue
                for mode in ('display', 'planning'):
                    p = estimate(m, now['soc'], target, now['v'], now['i'], age, sight['soc'], planning=mode == 'planning')
                    err[mode][target].append(p - now[key])
    return err


# ---- Evaluation ----

def evaluate(charges, model_for, first_sight=False):
    """Errors (predicted - observed minutes) for points below 89%, by target."""
    err = {'display': {100: [], 95: [], 80: []}, 'planning': {100: [], 95: [], 80: []}}
    firsts, by_charge = {}, {}
    for name, rows in charges.items():
        m = model_for(name)
        t0, start = rows[0]['t'], rows[0]['soc']
        for idx, r in enumerate(rows):
            if r['soc'] >= 89:
                continue
            age, s0 = (0.0, r['soc']) if first_sight else (r['t'] - t0, start)
            for target, key in ((100, 'tf'), (95, 't95'), (80, 't80')):
                if r[key] is None or r[key] <= 0:
                    continue
                for mode in ('display', 'planning'):
                    p = estimate(m, r['soc'], target, r['v'], r['i'], age, s0, planning=mode == 'planning')
                    err[mode][target].append(p - r[key])
                    by_charge.setdefault(name, {}).setdefault(mode, {}).setdefault(target, []).append(p - r[key])
                    if idx == 0:
                        firsts.setdefault(name, {}).setdefault(mode, {})[target] = round(p - r[key], 2)
    evaluate.by_charge = {n: {mode: {str(t): round(st.mean(abs(x) for x in e), 2) for t, e in d.items()} for mode, d in v.items()}
                          for n, v in by_charge.items()}
    return err, firsts


def summary(errs):
    return {str(t): {'points': len(e), 'mae': round(st.mean(abs(x) for x in e), 2),
                     'worst_short': round(min(e), 2), 'worst_long': round(max(e), 2),
                     'late_beyond_20_min_buffer': sum(x < -20 for x in e)} for t, e in errs.items()}


def v5_summary():
    """The released v5 predictions over the same points, from the v5 bundle's committed results."""
    path = V5 / 'expected-results.json'
    return json.load(open(path)) if path.exists() else None


def run():
    charges = load_charges()
    production = fit(charges)
    loco_models = {n: fit({k: v for k, v in charges.items() if k != n}) for n in charges}
    loco, loco_first = evaluate(charges, lambda n: loco_models[n])
    loco_by_charge = evaluate.by_charge
    insample, _ = evaluate(charges, lambda n: production)
    sight = evaluate_first_sight(charges, lambda n: loco_models[n], 0)
    watched = evaluate_first_sight(charges, lambda n: loco_models[n], AGE_INFERENCE_MINUTES)
    results = {
        'estimator': 'ut5-stock-pack-v6',
        'charges': {n: {'start_soc': rows[0]['soc'], 'samples': len(rows)} for n, rows in charges.items()},
        'leave_one_charge_out': {mode: summary(e) for mode, e in loco.items()},
        'leave_one_charge_out_first_estimates': loco_first,
        'leave_one_charge_out_mae_by_charge': loco_by_charge,
        'leave_one_charge_out_first_sight_mid_charge': {mode: summary(e) for mode, e in sight.items()},
        'leave_one_charge_out_first_sight_after_10_min': {mode: summary(e) for mode, e in watched.items()},
        'in_sample_production_constants': {mode: summary(e) for mode, e in insample.items()},
    }
    return charges, production, results


