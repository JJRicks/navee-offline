def rounded(m):
    """The model exactly as the generated Java sees it (constants rounded as printed)."""
    r = dict(m)
    for key in ('offset_mean', 'offset_depth_slope', 'depth_mean', 'depth_min', 'depth_max', 'offset_residual',
                'gauge_sigma', 'decay_display', 'decay_planning', 'finish_display', 'finish_planning', 'jump_lead',
                'jump_lead_planning'):
        r[key] = float('%.6f' % m[key])
    r['lead_display'] = [float('%.4f' % x) for x in m['lead_display']]
    r['lead_planning'] = [float('%.4f' % x) for x in m['lead_planning']]
    return r


def parity_java(charges, m):
    cases = []
    for name, rows in charges.items():
        t0, start = rows[0]['t'], rows[0]['soc']
        for r in rows[::40]:
            if r['soc'] >= 89:
                continue
            for target in (80, 90, 95, 100):
                for planning in (False, True):
                    p = estimate(m, r['soc'], target, r['v'], r['i'], r['t'] - t0, start, planning=planning)
                    cases.append('        {%r, %r, %r, %r, %r, %r, %d, %r}' % (r['soc'], float(target), r['v'], r['i'], r['t'] - t0, start, int(planning), p))
    body = ',\n'.join(cases)
    return f"""package com.jjricks.volt;

/** GENERATED by docs/validation/data/stock-pack-v6/fit_pack_model.py --write; do not edit. */
final class StockPackParity {{
    private StockPackParity() {{}}
    // soc, target, volts, amps, age minutes, start soc, planning (1/0), expected minutes from the Python model.
    static final double[][] CASES = {{
{body}
    }};
}}
"""


NUMBER = re.compile(r'-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?')


def same_numbers(committed, fresh, printed=False, absolute=0.0):
    """Same text around the numbers; numbers equal within their printed precision or absolute."""
    if NUMBER.sub('#', committed) != NUMBER.sub('#', fresh):
        return False
    a, b = NUMBER.findall(committed), NUMBER.findall(fresh)
    if len(a) != len(b):
        return False
    for x, y in zip(a, b):
        decimals = len(y.split('.')[1]) if '.' in y and 'e' not in y.lower() else 0
        # Printed constants keep the generator's format, so a shortened committed token fails.
        if printed and (len(x.split('.')[1]) if '.' in x and 'e' not in x.lower() else 0) != decimals:
            return False
        tolerance = 1.5 * 10 ** -decimals if printed and decimals else absolute
        if abs(float(x) - float(y)) > tolerance:
            return False
    return True


def same_json(committed, fresh):
    """Same structure; integers exact; two-decimal figures within one rounding step."""
    if isinstance(committed, dict):
        return isinstance(fresh, dict) and committed.keys() == fresh.keys() and all(same_json(committed[k], fresh[k]) for k in committed)
    if isinstance(committed, list):
        return isinstance(fresh, list) and len(committed) == len(fresh) and all(same_json(x, y) for x, y in zip(committed, fresh))
    if isinstance(committed, bool) or isinstance(committed, str) or committed is None:
        return type(committed) is type(fresh) and committed == fresh
    if type(committed) is int or type(fresh) is int:
        return type(committed) is int and type(fresh) is int and committed == fresh
    return type(committed) is float and type(fresh) is float and abs(committed - fresh) <= 0.0101


def check_helpers():
    """The comparisons must still reject drift they are meant to catch."""
    assert same_numbers('K = 0.215000;', 'K = 0.215001;', printed=True)
    assert not same_numbers('K = 0.2;', 'K = 0.215000;', printed=True)
    assert not same_numbers('K = 0.215000;', 'K = 0.217000;', printed=True)
    assert not same_numbers('{1.0, 2.0}', '{1.0, 2.0, 3.0}', absolute=1e-9)
    assert same_json({'n': 5129, 'mae': 2.90}, {'n': 5129, 'mae': 2.905})
    assert not same_json({'n': 5129.005}, {'n': 5129})
    assert not same_json({'n': 5129}, {'n': 5130})
    assert not same_json({'ok': True}, {'ok': 1})
    assert not same_json({'mae': 2.90}, {'mae': 2.92})


