#!/usr/bin/env python3
"""Fit and evaluate the UT5 MAX stock-charger pack model (estimator ut5-stock-pack-v6).

Standard library only. Reads the anonymized measurements already published in
../stock-startup-v5 and never needs a phone, scooter, account or network.

    python3 docs/validation/data/stock-pack-v6/fit_pack_model.py            # fit, evaluate, print summary
    python3 docs/validation/data/stock-pack-v6/fit_pack_model.py --check    # also verify committed outputs
    python3 docs/validation/data/stock-pack-v6/fit_pack_model.py --write    # regenerate committed outputs

The production constants in Ut5MaxStockPackModel.java and the parity table in
tests/StockPackParity.java are generated by --write. --check fails if either has drifted
from a fresh fit, or if the published evaluation numbers no longer reproduce. Comparisons are
numerical: platform math libraries may differ in the last bits of exp(), which must not fail
CI, while any change at the printed precision (or 1e-9 minutes for parity) still does.
"""
